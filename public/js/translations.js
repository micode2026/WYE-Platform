/* Language manager */
const Lang = {
  current: localStorage.getItem('lang') || 'en',

  t(key) {
    return TRANSLATIONS[this.current]?.[key]
        || TRANSLATIONS['en']?.[key]
        || key;
  },

  toggle() {
    this.current = this.current === 'en' ? 'ti' : 'en';
    localStorage.setItem('lang', this.current);
    document.documentElement.lang = this.current;
    document.body.classList.toggle('lang-ti', this.current === 'ti');
  },

  init() {
    document.documentElement.lang = this.current;
    document.body.classList.toggle('lang-ti', this.current === 'ti');
  }
};

/* Shorthand */
function t(key) { return Lang.t(key); }
